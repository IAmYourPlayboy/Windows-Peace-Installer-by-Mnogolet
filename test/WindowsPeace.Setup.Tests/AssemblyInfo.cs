using Xunit;

// Localization.Current — общий на весь процесс экземпляр (раздел 9 архитектуры:
// язык — сквозное состояние, как культура потока). Несколько тестов в этой
// сборке переключают его язык и возвращают обратно, а другие тесты в это же
// время читают NextTitle по умолчанию, зависящий от того же языка. При
// параллельном запуске классов тестов это гонка: соседний тест успевал
// переключить язык между чтением и обратным возвратом. Сборка запускается
// последовательно — цена в скорости тестов ничтожна, а находка гонки заново
// стоила бы дороже отладки, чем сама последовательность.
[assembly: CollectionBehavior(DisableTestParallelization = true)]
